// ============================================================
//  第一课补充：温度参数与 token 限制
//  （模型输出有多随机？最多能说多少？一次调用花多少钱？）
//
//  🏠 生活化比喻：
//  模型写句子是一个词一个词往外蹦的。每写下一个词之前，
//  它手里其实攥着一张「候选词清单」，每个词都带一个概率分数。
//  temperature（温度）就是决定「怎么从清单里挑词」的那颗骰子的面数：
//    温度 → 0 ：两面骰——几乎总落在分数最高的那个「最稳的词」上，
//                所以同一句提示词反复问，答案几乎逐字相同
//    温度调高 ：百面骰——冷门词也有机会被掷中，用词更多变、更意外，
//                重跑几次输出的差异也肉眼可见
//  max_tokens 则是「便签纸的大小」：模型的回答只能写在这张纸上，
//  写满了就必须停笔——哪怕一句话才写到一半。
//  而 response 里的 usage 就像这次调用的「账单小票」：
//  进去多少 token、出来多少 token，一项一项列得清清楚楚，
//  这一次调用花多少钱，全靠它来算。
//
//  学习目标：
//  1. 理解温度参数如何影响模型输出的稳定性和创造性
//  2. 理解 max_tokens 如何限制输出上限，并认出「被截断」的信号
//  3. 学会查看 usage 用量统计，估算一次调用的 token 成本
//
//  核心结论：
//  - 温度越低输出越稳：适合分类、抽取、评测——agent 开发里
//    绝大多数「干活的步骤」都用低温度
//  - 温度越高输出越发散：适合头脑风暴、命名、创意写作
//  - 温度只改「选词的保守程度」，不改模型的「知识」（见第二段 ⚠️）
//  - max_tokens 不是「期望长度」而是「输出上限」：写满被截断时，
//    结束原因（finish_reason）是 "length" 而不是 "stop"
// ============================================================

// ============================================================
//  第一段：导入模块 + 固定不变的实验条件
// ============================================================
//  这个文件本质上是一张「实验表」：模型、提示词统统固定，
//  每次只拧温度 / max_tokens 中的一个旋钮，看输出怎么变。
//  控制变量的思路和第二课一样——一次只动一个，差异才能归因。

import "dotenv/config";
// 副作用导入：把 .env 里的 OPENAI_API_KEY 等变量搬进 process.env
// （第一课讲过的「搬运工」，这里一句话带过）。

import client from "./src/openai-charles-client";
// 真正干活的客户端实例（「官方电话总机」）。它是第一课客户端的
// Charles 抓包加强版：平时发请求的行为和 new OpenAI(...) 完全一样，
// 只多三行 [Charles Debug] 体检单日志；设了 USE_CHARLES=1 才走代理，
// 机制详见 src/openai-charles-client.ts 的头部注释。

// const client = new OpenAI({ apiKey: process.env.OPENAI_API_KEY });
// ↑ 被注释保留的「原始写法」：不需要抓包时，用这一行直接建客户端
//   就够了。两行二选一——现在实际生效的是上面 import 进来的版本。

const model = process.env.OPENAI_MODEL || "gpt-4o-mini";
// 模型名从 .env 读，没设就用默认值 gpt-4o-mini（便宜、快，适合学习）。
// || 的意思：「左边有值用左边，左边是空就用右边」。

const prompt =
  "为面向开发者的可视化 AI 工作流构建器生成 5 个产品名称。";
// 所有实验都用这同一句提示词——它是实验里「固定不动的那个变量」。
// 问题不变，输出差异才能归因给温度 / max_tokens，而不是给问题。
// （后面所有 📤 走查引用的都是这句原文。）

// ============================================================
//  第二段：complete() —— 把一次模型调用打包成「拿数据」的函数
// ============================================================
//  输入两个旋钮（温度、上限），返回三样实验要观察的数据：
//  回复文本、结束原因、用量小票。真实项目里把模型调用包成这种
//  函数很常见：方便复用，也方便统一加日志和错误处理。

async function complete(temperature: number, maxTokens: number) {
  // async：函数体内要 await 网络请求，所以声明为异步函数
  // （第一课讲过，一句话带过）。
  const response = await client.chat.completions.create({
    model: model,
    temperature,
    // ↑ 属性简写：变量名和参数名恰好都叫 temperature，
    //   就可以只写一个词，等价于 temperature: temperature。
    //
    // ⚠️ 高危易错点：温度只改「选词的保守程度」，不改模型的「知识」。
    //   调高温度不会让模型多懂任何东西，只会让它更敢挑冷门词；
    //   想让回答更准，靠的是换更强的模型、写更好的提示词、喂参考资料，
    //   而不是调温度。温度管的是措辞的「稳与野」，管不了事实的对与错。
    max_tokens: maxTokens,
    // ↑ 不能简写：变量名是 maxTokens（驼峰），参数名是 max_tokens
    //   （蛇形），两个名字不同，必须老老实实写「参数名: 变量名」。
    //   max_tokens 限制「最多生成多少 token」——便签纸就这么大，
    //   写满了就得停，哪怕回答还没说完（观察调用 5）。
    messages: [{ role: "user", content: prompt }],
    // messages 只有一条 user 消息：上一课对比的是「谁在说」（角色），
    // 这一课对比的是「旋钮拧到哪」（参数），所以角色保持最简。
  });
  // 这一行真正发出 HTTP 请求（要花钱！main() 一共会跑 5 次）。

  const choice = response.choices[0];
  // choices 是候选回复数组，普通调用只有 1 个候选，取 [0] 即可。

  return {
    text: choice.message.content ?? "",
    // ?? 是空值合并：content 的类型是 string | null，
    // 为 null 时取右边的 ""，保证 text 永远是字符串——
    // 后面的打印和 first === second 比较都不会被 null 绊倒。
    finishReason: choice.finish_reason,
    // 结束原因，本课重点看两种值：
    //   "stop"   → 模型觉得说完了，正常收笔
    //   "length" → 便签纸写满了，被迫截断（见调用 5 的走查）
    usage: response.usage,
    // usage = 本次调用的「账单小票」（算钱走查见第三段）。
    // 类型上它可能是 undefined，所以第三段打印前先判空。
  };
}

// ============================================================
//  第三段：runCase() —— 实验记录员：跑一组参数并打印观察报告
// ============================================================
//  把「跑一次实验 + 按固定格式打印」封装起来，main() 里就只剩
//  一张干净的实验表（5 行调用），每行参数的差别一眼可见。

async function runCase(label: string, temperature: number, maxTokens: number) {
  const result = await complete(temperature, maxTokens);
  // 参数原样转交给 complete()，自己只负责「怎么展示」。

  console.log(label);
  console.log(`设置：温度参数=${temperature}，最大 token 数=${maxTokens}`);
  // 反引号模板字符串：${} 里的变量会被替换成实际值。
  // 比如调用 3 的实参是 (0.7, 120)，这行就打印：
  //   设置：温度参数=0.7，最大 token 数=120

  console.log("\n输出：");
  console.log(result.text);
  console.log("\n结束原因：", result.finishReason);

  if (result.usage) {
    console.log(
      `token 用量：提示词=${result.usage.prompt_tokens}，补全=${result.usage.completion_tokens}，总计=${result.usage.total_tokens}`
    );
  }
  // 先判空再打印：usage 的类型含 undefined（某些服务/场景不返回它），
  // 不判空直接读 result.usage.prompt_tokens 可能直接抛错。
  //
  // 📤 输入输出走查（usage = 账单小票，代一组假设数字算一次钱）：
  //   假设这次调用的小票是（数字为示意，真实数字以你运行时打印为准）：
  //     prompt_tokens     = 25    提示词那句中文折算成的 token 数（进）
  //     completion_tokens = 95    模型生成的 5 个产品名（出，通常更贵）
  //     total_tokens      = 120   = 25 + 95，两项相加就是它
  //   按公开价目举例（gpt-4o-mini 官网价：输入 $0.15 / 输出 $0.60，
  //   每百万 token；价目请以服务商当期页面为准）：
  //     输入花费  25 × 0.15 ÷ 1,000,000 ≈ $0.0000038
  //     输出花费  95 × 0.60 ÷ 1,000,000 ≈ $0.0000570
  //     合计约 $0.00006 —— 单次看似不起眼，但本文件 main() 一跑
  //     就是 5 次，agent 的循环动辄几十上百次调用：
  //     成本意识，就从看懂这张小票开始。

  console.log("-".repeat(60));
  return result.text;
  // 把文本返回给调用方——main() 要拿它做「两次输出是否一致」的比较。
}

// ============================================================
//  第四段：main() —— 一张 5 行的实验表
// ============================================================
//  五次调用 = 五次真实 API 请求（要花钱、要 OPENAI_API_KEY）：
//    调用 1、2：温度 0   × 上限 120 —— 验证「低温是否稳定」
//    调用 3：  温度 0.7 × 上限 120 —— 常用的「平衡档」
//    调用 4：  温度 1.2 × 上限 120 —— 高温看发散
//    调用 5：  温度 0.7 × 上限 20  —— 故意把便签纸撕小，看截断

async function main() {
  console.log("提示词：");
  console.log(prompt);
  console.log("-".repeat(60));
  // 先把固定变量亮出来：每次看输出之前，先确认「问题没变」。

  const first = await runCase("调用 1", 0, 120);
  const second = await runCase("调用 2", 0, 120);
  // 温度参数为 0 并不代表数学意义上的“永远完全相同”，
  // 但它通常会显著降低随机性，适合观察稳定输出。
  // （用骰子说：两次都是两面骰，都掷向那个最稳的词，
  //   所以两段文字逐字重合的概率很高，但不是 100%。）
  console.log("温度参数为 0 的两次输出是否完全一致：", first === second);
  // === 比较字符串时比的是「内容」：两个字符串逐字相同才是 true。
  //
  // 📤 输入输出走查（同一句提示词 × 不同温度，预期看到的对比）：
  //   固定不变：model、提示词原文（上面打印的那句）、max_tokens=120
  //
  //   调用 1  温度=0    → 预期：5 个名字偏「安全牌」，词根直白规矩
  //   调用 2  温度=0    → 预期：与调用 1 几乎逐字相同（上面多半 true）
  //   调用 3  温度=0.7  → 预期：大方向接近，个别名字换了花样
  //   调用 4  温度=1.2  → 预期：明显更敢想，和前三组的差异一眼可辨
  //
  //   （以上是预期趋势，不是运行记录——具体输出每次都可能不同；
  //     温度只是「骰子的面数」，具体掷出什么由服务端采样决定。）
  console.log("-".repeat(60));

  await runCase("调用 3", 0.7, 120);
  await runCase("调用 4", 1.2, 120);
  // 温度从 0.7 升到 1.2，其余条件不动：观察输出从「稳」到「野」。

  await runCase("调用 5", 0.7, 20);
  // 最后一组故意把最大 token 数设小，方便观察输出被限制时的效果。
  //
  // 📤 输入输出走查（调用 5：max_tokens=20 时预期发生什么）：
  //   温度仍是 0.7，只把便签纸从 120 格撕到 20 格——
  //   5 个产品名几乎不可能塞进 20 个 token，预期看到：
  //     输出     → 只有 1~2 个名字，甚至一句话写到一半就断
  //     结束原因 → "length"（纸写满了被迫停笔），不再是 "stop"
  //     小票     → 补全一项 completion_tokens 顶在 20 附近
  //   这就是「截断」：内容没写完，预算先花光。真实项目里拿到 "length"
  //   要当异常处理（加大上限 / 重试 / 让模型少列几项），
  //   否则半截 JSON、半截工具参数会顺着管道流进下游步骤。
}

main().catch(console.error);
